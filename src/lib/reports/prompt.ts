export function reportUserPrompt(source: string, instructions?: string) {
  return `${source}\n\n${instructions?.trim() ? `추가 지시사항: ${instructions.trim()}\n\n` : ""}위 자료로 주간 팀 보고서를 작성해 주세요.`;
}
